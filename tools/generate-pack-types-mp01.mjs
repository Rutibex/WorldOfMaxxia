/** Derive TS declarations from the frozen contract subset; JSON Schema stays authoritative. */
import {readFile,writeFile} from 'node:fs/promises';
const base=new URL('../contracts/mp01/',import.meta.url);
const names=['common','pack','content-index','character','catalogue-lock','transfer','catalogue'];
const schemas=new Map();for(const n of names)schemas.set(n,JSON.parse(await readFile(new URL('schemas/'+n+'.schema.json',base),'utf8')));
const title=s=>s.split(/[-_]/).map(v=>v[0].toUpperCase()+v.slice(1)).join('');
function render(v){
 if(v.$ref){const [file,fragment]=v.$ref.split('#');const type=title(file.replace('.schema.json',''));return fragment?type+title(fragment.split('/').at(-1)):type;}
 if(v.const!==undefined)return JSON.stringify(v.const);
 if(v.enum)return v.enum.map(x=>JSON.stringify(x)).join(' | ');
 if(v.allOf)return v.allOf.filter(x=>x.type||x.$ref||x.enum||x.const!==undefined).map(x=>'('+render(x)+')').join(' & ')||'unknown';
 if(v.oneOf)return v.oneOf.map(x=>'('+render(x)+')').join(' | ');
 if(Array.isArray(v.type))return v.type.map(t=>render({...v,type:t})).join(' | ');
 if(v.type==='array')return `Array<${render(v.items)}>`;
 if(v.type==='object'){
  const props=Object.entries(v.properties??{}).map(([k,x])=>`${JSON.stringify(k)}${(v.required??[]).includes(k)?'':'?'}: ${render(x)};`);
  if(v.additionalProperties!==false)props.push(`[key: string]: ${v.additionalProperties&&typeof v.additionalProperties==='object'?render(v.additionalProperties):'unknown'};`);
  return '{ '+props.join(' ')+' }';
 }
 return {string:'string',integer:'number',number:'number',boolean:'boolean',null:'null'}[v.type]??'unknown';
}
let text='// Generated by tools/generate-pack-types-mp01.mjs; edit schemas, not this file.\n// Runtime validators enforce patterns, bounds and cross-record rules not expressed by TS.\n';
for(const [name,s] of schemas){if(s.$defs)for(const [k,v] of Object.entries(s.$defs))text+=`export type ${title(name)+title(k)} = ${render(v)};\n`;else text+=`export type ${title(name)} = ${render(s)};\n`;}
const path=new URL('types.d.ts',base);
if(process.argv.includes('--check')){if(await readFile(path,'utf8')!==text)throw Error('Stale pack contract declarations');console.log('PASS: generated contract declarations match schemas.');}else{await writeFile(path,text);console.log('Generated pack contract declarations.');}
