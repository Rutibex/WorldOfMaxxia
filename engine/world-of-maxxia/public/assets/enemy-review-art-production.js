export function animationClip(atlas, name) {
    if (name === 'telegraph' || name === 'discharge' || name === 'recovery') {
        if (!atlas.special) throw new Error(`No boss special animation for ${name}`);
        return atlas.special.clips[name];
    }
    return atlas.clips[name];
}
export function clipFrame(clip, elapsed, reduced = false) {
    if (reduced) return clip.frames[clip.loop ? 0 : clip.frames.length - 1];
    const n = Math.floor(Math.max(0, elapsed) / clip.ms);
    return clip.frames[clip.loop ? n % clip.frames.length : Math.min(n, clip.frames.length - 1)];
}
export function clipDuration(name, atlas = DUST_IMP) {
    const c = animationClip(atlas, name);
    return c.frames.length * c.ms;
}
export const PORTRAIT_PROOF = 5;
export const PORTRAIT_STATES = [
    'normal',
    'hurt',
    'afflicted',
    'dead'
];
import { PORTRAITS, portraitForLegacyNumber } from '../shared/content/actors.ts';
let portraitResources = null;
export function configurePortraitArt(resolver) {
    portraitResources = resolver;
}
export function portraitSetAsset(id, number, state) {
    const set = PORTRAITS[id ?? portraitForLegacyNumber(number)];
    const resource = set && portraitResources?.byId.get(set.states[state]);
    return resource?.url ?? portraitAsset(number, state);
}
export function portraitAsset(index, state) {
    if (!Number.isInteger(index) || index < 0 || index >= 12) return null;
    return index === PORTRAIT_PROOF ? `assets/art/witch-${state}.png` : `assets/art/portraits/${String(index).padStart(2, '0')}-${state}.png`;
}
export function tavernFrame(elapsed, reduced = false) {
    if (reduced) return 0;
    const t = Math.max(0, elapsed) % 3600;
    return t < 2300 ? 0 : t < 2420 ? 1 : t < 2540 ? 2 : 3;
}
